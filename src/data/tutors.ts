// Helper function to get tutors by category
export const getTutorsByCategory = (categoryName: string): any[] => {
  const category = categories.find((cat) => cat.name === categoryName);
  if (!category) return [];

  return tutors.filter((tutor) =>
    tutor.subjects.some((subject: string) => category.subjects.includes(subject))
  );
};

// Get popular tutors (highest rated with most reviews)
export const getPopularTutors = (): any[] => {
  return [...tutors]
    .sort((a, b) => {
      const scoreA = a.rating * Math.log(a.reviewCount + 1);
      const scoreB = b.rating * Math.log(b.reviewCount + 1);
      return scoreB - scoreA;
    })
    .slice(0, 8);
};
